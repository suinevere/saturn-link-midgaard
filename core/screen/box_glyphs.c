unsigned char box_glyph_map(unsigned char c)
{
    if (c >= 0x20 && c < 0x80) return c;
    if (c < 0x20) return ' ';
    {
        unsigned char g = HIGH_MAP[c - 0x80];
        return g ? g : (unsigned char) '?';
    }
}

const unsigned char *box_glyph_rows(unsigned char code)
{
    if (code < BOX_GLYPH_FIRST || code >= BOX_GLYPH_FIRST + BOX_GLYPH_COUNT) return 0;
    return GLYPH_ROWS[code - BOX_GLYPH_FIRST];
}
